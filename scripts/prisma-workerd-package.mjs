#!/usr/bin/env node
// ---------------------------------------------------------------------------
// THE WORKERD PRISMA CLIENT AS ONE PACKAGE, SO THE BUNDLE HOLDS ONE COPY
// (owner's ruling 2026-11-16, GAPS 36 / GAPS 44).
//
//   node scripts/prisma-workerd-package.mjs      (run by `npm run build`)
//
// WHY. The generated client lives in `src/generated/prisma-workerd` — app
// source to Turbopack, so it is compiled into every chunk group that imports
// it. At `bed6b3a` OpenNext's esbuild metafile held FIVE copies, each found by
// the same 964,468-byte literal (Prisma's encoded query data) beside the whole
// schema as text: the pages' group, `/login`'s, and three groups of route
// handlers — ~8.2 MB of the 19.2 MB handler — and the 3.68 MB query compiler
// `.wasm` twice. `@prisma/client`, which Next lists as a server external by
// default, appeared ONCE: Turbopack leaves an external as a `require` and
// OpenNext's esbuild bundles it a single time. So the client is made a package
// and named in `serverExternalPackages` (next.config.ts), and the copies are
// whatever esbuild makes of one module: one.
//
// WHAT IT WRITES. `node_modules/@zebra/prisma-workerd/`: `index.mjs` (the
// generated `client.ts` compiled by esbuild, every bare import left external
// so `@prisma/client` stays the one copy it already is), the `.wasm` beside it
// for the `?module` import wrangler compiles ahead of time, and a
// `package.json`. Under `node_modules` because that is where a package name
// resolves; regenerated by every build, so `npm ci` wiping it costs nothing.
// Refuses — exit 1, by name — when the generated client is not there.
// ---------------------------------------------------------------------------
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const PACKAGE_NAME = '@zebra/prisma-workerd'
export const WASM = 'query_compiler_fast_bg.wasm'

/** The package's own `package.json`, as an object. */
export const packageJson = () => ({
  name: PACKAGE_NAME,
  private: true,
  type: 'module',
  main: './index.mjs',
  exports: { '.': './index.mjs' },
  sideEffects: false,
})

/**
 * The esbuild plugin that writes the compiler's `?module` import as the
 * ABSOLUTE path of the package's own `.wasm`, for OpenNext's
 * `wrangler-externals` plugin and wrangler to load at deploy.
 *
 * NOT RELATIVE, because which copy of `index.mjs` OpenNext's esbuild bundles
 * depends on the platform: on Windows it resolved the package under the root
 * `node_modules`, and on CI's Linux it took the copy Next's trace put in the
 * server function — where the `.wasm` is left out on purpose (next.config.ts)
 * — and the dry run failed with no size (run 43826422641, `c54b0ae`). One
 * absolute path is valid whichever copy is bundled.
 * @param {string} wasmPath  the `.wasm` beside the package's `index.mjs`
 */
export const keepWasmModule = (wasmPath) => ({
  name: 'keep-wasm-module',
  setup(build) {
    build.onResolve({ filter: /\.wasm\?module$/ }, ({ path }) => ({
      path: `${wasmPath.replace(/\\/g, '/')}?module`,
      external: true,
      ...(path.endsWith(`${WASM}?module`)
        ? {}
        : { errors: [{ text: `unexpected wasm import ${path}` }] }),
    }))
  },
})

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const source = join(root, 'src', 'generated', 'prisma-workerd')
  const entry = join(source, 'client.ts')
  const wasm = join(source, 'internal', WASM)
  for (const file of [entry, wasm])
    if (!existsSync(file))
      throw new Error(`${file} is missing — run \`prisma generate\` first`)

  const out = join(root, 'node_modules', ...PACKAGE_NAME.split('/'))
  mkdirSync(out, { recursive: true })
  const { build } = await import('esbuild')
  const result = await build({
    entryPoints: [entry],
    outfile: join(out, 'index.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'esnext',
    packages: 'external',
    plugins: [keepWasmModule(join(out, WASM))],
    logLevel: 'warning',
    metafile: true,
  })
  copyFileSync(wasm, join(out, WASM))
  writeFileSync(
    join(out, 'package.json'),
    `${JSON.stringify(packageJson(), null, 2)}\n`,
  )
  const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0
  console.log(
    `${PACKAGE_NAME}: index.mjs ${bytes} bytes + ${WASM}, from src/generated/prisma-workerd`,
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(`prisma-workerd-package: ${error.message} — NOT OK`)
    process.exit(1)
  })
}
